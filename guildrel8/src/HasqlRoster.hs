-- ANCHOR: all
{-# LANGUAGE OverloadedStrings #-}

-- ⚡ The roster with hasql: statements as values.
-- hasql の名簿：問い合わせを値として作る
module HasqlRoster
  ( connectGuild
  , runSession
  , createTables
  , strong
  , strongBroken
  ) where

import Data.Int  (Int32)
import Data.Text (Text)
import Hasql.Connection                    (Connection)
import Hasql.Connection                    qualified as Connection
import Hasql.Connection.Setting            qualified as Setting
import Hasql.Connection.Setting.Connection qualified as Setting
import Hasql.Decoders                      qualified as D
import Hasql.Encoders                      qualified as E
import Hasql.Session                       (Session)
import Hasql.Session                       qualified as Session
import Hasql.Statement                     (Statement (..))

-- ANCHOR: connect
-- 🔌 Connect with a URL such as postgresql://user:pass@host/db.
-- postgresql://ユーザー:パスワード@ホスト/DB のような URL で接続する
connectGuild :: Text -> IO Connection
connectGuild url = do
  result <- Connection.acquire [Setting.connection (Setting.string url)]
  either (fail . show) pure result

-- 📮 Run a session, and turn an error into an IO error.
-- セッションを動かす。エラーなら IO のエラーにする
runSession :: Connection -> Session a -> IO a
runSession conn session = do
  result <- Session.run session conn
  either (fail . show) pure result
-- ANCHOR_END: connect

-- ANCHOR: create
-- 🧱 Make the tables (a script: no parameters, no results).
-- 表を作る（スクリプト：穴もなく、結果もない）
createTables :: Session ()
createTables = Session.sql
  "CREATE TABLE IF NOT EXISTS adventurers \
  \  ( id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY \
  \  , name  TEXT    NOT NULL UNIQUE \
  \  , job   TEXT    NOT NULL \
  \  , level INTEGER NOT NULL ); \
  \CREATE TABLE IF NOT EXISTS quests \
  \  ( id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY \
  \  , title    TEXT    NOT NULL \
  \  , taken_by INTEGER REFERENCES adventurers (id) );"
-- ANCHOR_END: create

-- ANCHOR: statement
-- 💪 Names and levels of this level or more, the strongest first.
-- このレベル以上の名前とレベルを、強い順に
strong :: Statement Int32 [(Text, Int32)]
strong = Statement sql encoder decoder True
  where
    sql =
      "SELECT name, level FROM adventurers \
      \WHERE level >= $1 ORDER BY level DESC"
    encoder = E.param (E.nonNullable E.int4)
    decoder = D.rowList row
    row     = (,) <$> D.column (D.nonNullable D.text)
                  <*> D.column (D.nonNullable D.int4)
-- ANCHOR_END: statement

-- ANCHOR: broken
-- 🐞 The same, but it reads the level as text by mistake.
-- 同じ問い合わせ。ただし、まちがえてレベルを文字列として読む
strongBroken :: Statement Int32 [(Text, Text)]
strongBroken = Statement sql encoder decoder True
  where
    sql =
      "SELECT name, level FROM adventurers \
      \WHERE level >= $1 ORDER BY level DESC"
    encoder = E.param (E.nonNullable E.int4)
    decoder = D.rowList row
    row     = (,) <$> D.column (D.nonNullable D.text)
                  <*> D.column (D.nonNullable D.text)
-- ANCHOR_END: broken
-- ANCHOR_END: all
